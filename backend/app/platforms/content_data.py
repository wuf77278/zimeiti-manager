def _normalize_platform(platform: str) -> str:
    normalized = (platform or "wechat_channels").replace("-", "_")
    if normalized in {"wechat", "video号", "channels"}:
        return "wechat_channels"
    if normalized in {"douyin", "抖音"}:
        return "douyin"
    return normalized if normalized in {"douyin", "wechat_channels"} else "wechat_channels"


def _normalize_category(platform: str, category: str) -> str:
    raw = (category or "").strip() or ("interest" if platform == "douyin" else "local")
    if platform == "douyin":
        return DOUYIN_ALIASES.get(raw, raw if raw in DOUYIN_CONTENT_DATA else "interest")
    return WECHAT_ALIASES.get(raw, raw if raw in WECHAT_CHANNELS_CONTENT_DATA else "local")


def _reference_count(profile: dict[str, Any]) -> int:
    total = 0
    for key in ["sample_titles", "hook_patterns", "comment_patterns", "content_formulas", "metric_focus", "risk_notes"]:
        total += len(profile.get(key) or [])
    for group in profile.get("keyword_packs") or []:
        total += len(group.get("items") or [])
    return total


def get_platform_content_profile(platform: str, category: str) -> dict[str, Any]:
    """Return a serializable content profile for the platform/category."""
    normalized_platform = _normalize_platform(platform)
    normalized_category = _normalize_category(normalized_platform, category)
    data = DOUYIN_CONTENT_DATA if normalized_platform == "douyin" else WECHAT_CHANNELS_CONTENT_DATA
    profile = deepcopy(data[normalized_category])
    risk_notes = profile.get("risk_notes") or []
    profile["platform"] = normalized_platform
    profile["category"] = normalized_category
    profile["data_scope"] = DATA_SCOPE
    profile["risk_notes"] = [*risk_notes, *COMMON_RISK_NOTES]
    profile["reference_count"] = _reference_count(profile)
    return profile


def build_content_data_summary(
    platform: str,
    category: str,
    *,
    agent_type: str = "general",
    max_items: int = 4,
) -> str:
    """Build a compact prompt block from the platform content profile."""
    profile = get_platform_content_profile(platform, category)
    platform_label = "抖音号" if profile["platform"] == "douyin" else "微信视频号"
    category_label = profile["category_label"]

    def join_items(key: str) -> str:
        return " / ".join(str(item) for item in (profile.get(key) or [])[:max_items])

    keyword_lines = []
    for group in (profile.get("keyword_packs") or [])[:3]:
        keyword_lines.append(f"- {group['label']}：{'、'.join(group.get('items', [])[:6])}")

    include_visual = agent_type in {"visual", "judge", "general"}
    include_comments = agent_type in {"user_sim", "growth", "judge", "general"}
    include_formulas = agent_type in {"content", "growth", "judge", "general"}

    lines = [
        f"\n\n## 平台内容数据参考（{platform_label} / {category_label}）",
        f"- 数据口径：{profile['data_scope']}",
        f"- 参考项数量：{profile['reference_count']}",
        f"- 高频标题结构：{join_items('sample_titles')}",
        f"- 前3秒/开场钩子：{join_items('hook_patterns')}",
    ]
    if include_formulas:
        lines.append(f"- 内容公式：{join_items('content_formulas')}")
    if include_comments:
        lines.append(f"- 评论语境：{join_items('comment_patterns')}")
    if include_visual:
        lines.append(f"- 指标关注：{join_items('metric_focus')}")
    if keyword_lines:
        lines.append("- 关键词包：\n" + "\n".join(keyword_lines))
    lines.append(f"- 风险提醒：{join_items('risk_notes')}")
    return "\n".join(lines)


def reference_comments(platform: str, category: str, limit: int = 3) -> list[str]:
    """Return comment archetypes for deterministic report enrichment."""
    profile = get_platform_content_profile(platform, category)
    return list((profile.get("comment_patterns") or [])[:limit])
